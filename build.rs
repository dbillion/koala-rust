// build.rs - compile WAT plugins to WASM at build time and generate Rust module
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let plugins = ["hash-tools", "text-transform", "json-tools"];
    let out_dir = env::var("OUT_DIR").unwrap();
    let out_path = PathBuf::from(&out_dir);

    let mut generated = String::new();
    generated.push_str("// Generated by build.rs - DO NOT EDIT\n\n");

    for name in plugins {
        let wat_path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("plugins")
            .join("wasm")
            .join(format!("{}.wat", name));
        let wasm_path = out_path.join(format!("{}.wasm", name));

        let wat_source =
            fs::read_to_string(&wat_path).expect(&format!("Failed to read {}", wat_path.display()));
        let wasm_bytes = wat::parse_str(&wat_source).expect(&format!("Failed to parse {}", name));
        fs::write(&wasm_path, &wasm_bytes)
            .expect(&format!("Failed to write {}", wasm_path.display()));

        println!("cargo:rerun-if-changed={}", wat_path.display());
        println!(
            "Compiled {} -> {} ({} bytes)",
            wat_path.display(),
            wasm_path.display(),
            wasm_bytes.len()
        );

        // Generate static byte array
        let const_name = name.replace("-", "_").to_uppercase();
        generated.push_str(&format!(
            "pub const {}_WASM: &[u8] = include_bytes!(\"{}.wasm\");\n\n",
            const_name, name
        ));
    }

    // Write generated module
    let generated_path = out_path.join("wasm_plugins.rs");
    fs::write(&generated_path, generated).expect("Failed to write generated module");
}
